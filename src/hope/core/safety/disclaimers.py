from typing import Dict, List
from dataclasses import dataclass


@dataclass
class SafetyDisclaimer:
    """A safety disclaimer with multi-language support."""
    
    key: str
    languages: Dict[str, str]
    
    def get(self, language: str = "en") -> str:
        """Get disclaimer in requested language, fallback to English."""
        return self.languages.get(language[:2].lower(), self.languages["en"])


