def get_crisis_hotline(country_code: str = "US") -> CrisisHotline:
    """Get crisis hotline for country, fallback to US."""
    return CRISIS_HOTLINES.get(country_code.upper(), CRISIS_HOTLINES["US"])


def format_crisis_message(
    language: str = "en",
    country_code: str = "US",
) -> str:
    """
    Format complete crisis message with hotline.
    
    Returns ready-to-display crisis support message.
    """
    hotline = get_crisis_hotline(country_code)
    
    message = f"""
{CRISIS_HEADER.get(language)}

📞 {hotline.hotline_name}: {hotline.phone_number}

{CRISIS_REASSURANCE.get(language)}

{HUMAN_ESCALATION.get(language)}
""".strip()
    
    return message


